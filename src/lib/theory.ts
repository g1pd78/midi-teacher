/**
 * Какие элементы нотной записи есть в пьесе (MEI после Verovio).
 * Порядок — как в `CARDS`: сначала самое базовое.
 */
export function detectFeatures(mei: string, structure: MeiStructure, notes: ScoreNote[]): string[] {
  const found = new Set<string>(["staff", "meter", "durations", "fingering"]);
  const clefs = [...structure.clefOf.values()];
  if (clefs.includes("G")) found.add("treble-clef");
  if (clefs.includes("F")) found.add("bass-clef");
  if (structure.staves >= 2) found.add("grand-staff");
  for (const n of notes) {
    const clef = structure.clefOf.get(n.staff) ?? "G";
    if ((clef === "G" && (n.pitch <= 60 || n.pitch >= 81)) || (clef === "F" && (n.pitch >= 60 || n.pitch <= 40))) found.add("ledger");
  }
  const has = (re: RegExp) => re.test(mei);
  if (has(/<note\b[^>]*\bdur="(8|16|32)"|<chord\b[^>]*\bdur="(8|16)"/)) found.add("eighths");
  if (has(/\bdots="\d"/)) found.add("dot");
  if (has(/<tie\b|\btie="[im]"/)) found.add("tie");
  if (has(/<tuplet\b/)) found.add("triplet");
  if (has(/<rest\b|<mRest\b/)) found.add("rests");
  if (has(/\b(right|left)="(dbl|end)"/)) found.add("barlines");
  if (has(/\b(right|left)="rpt(start|end|both)"/)) found.add("repeat");
  if (has(/\baccid="[sf]"|<accid\b[^>]*\baccid="[sf]"/)) found.add("sharp-flat");
  if (has(/\baccid="n"|<accid\b[^>]*\baccid="n"/)) found.add("natural");
  if (has(/\b(key\.sig|keysig)="[1-7][sf]"|<keySig\b[^>]*\bsig="[1-7][sf]"/)) found.add("key-signature");
  if (has(/<slur\b/)) found.add("slur");
  if (has(/\bartic="[^"]*stacc/)) found.add("staccato");
  if (has(/\bartic="[^"]*\bacc\b/)) found.add("accent");
  if (has(/<fermata\b|\bfermata="/)) found.add("fermata");
  if (has(/<dynam\b/)) found.add("dynamics");
  if (has(/<hairpin\b/)) found.add("hairpins");
  if (has(/<tempo\b/)) found.add("tempo");
  if (has(/<pedal\b/)) found.add("pedal");
  if (has(/<chord\b/)) found.add("chord");
  return CARDS.map((c) => c.id).filter((id) => found.has(id));
}

/** Элементы, которые вводит ступень тренажёра нот. */
export function trainerFeatures(level: number, grandStaff: boolean, bass: boolean): string[] {
  const out = ["staff"];
  if (!bass || grandStaff) out.push("treble-clef");
  if (bass || grandStaff) out.push("bass-clef");
  if (grandStaff) out.push("grand-staff");
  if (level >= 8) out.push("ledger");
  if (level >= 9) out.push("sharp-flat");
  return out;
}

/** Элементы табулатуры в пьесе: подписи приёмов, каподастр, строй. */
export function tabFeatures(mei: string, opts: { capo: number; tuningChanged: boolean; fingers: boolean; bass?: boolean; drums?: boolean }): string[] {
  const found = new Set<string>(["tab", "strings-frets"]);
  const labels = [...mei.matchAll(/<rend[^>]*fontsize="x-small"[^>]*>([^<]*)<\/rend>/g)].flatMap((m) => m[1].split(" "));
  const has = (l: string) => labels.includes(l);
  if (opts.fingers || labels.some((l) => /^[1-4]$/.test(l))) found.add("left-fingers");
  if (opts.tuningChanged) found.add("tuning");
  if (opts.capo > 0) found.add("capo");
  if (has("H") || (has("P") && !has("T"))) found.add("hammer-pull");
  if (has("T")) found.add("slap");
  // p и a бывают только у гитары (классическая техника), i–m без них — чередование на басу.
  if (has("p") || has("a")) found.add("pima");
  else if (has("i") || has("m")) found.add("finger-alt");
  if (opts.bass && opts.drums) found.add("groove");
  if (has("↗") || has("↘")) found.add("slide");
  if (labels.some((l) => /^B/.test(l))) found.add("bend");
  if (has("PM")) found.add("palm-mute");
  if (has("~")) found.add("vibrato");
  if (has("X")) found.add("dead-note");
  if (has("Harm") || has("P.H.")) found.add("harmonics");
  if (has("↓") || has("↑")) found.add("strum");
  // Аккорды над табами — схемы; пауэр-аккорды и баррэ — по их формам.
  const harms = [...mei.matchAll(/<harm\b[^>]*>([^<]+)<\/harm>/g)].map((m) => m[1].trim());
  if (opts.bass) {
    // Бас: буквы над нотами — аккорды остальных, по ним строится линия.
    if (harms.length) found.add("bass-line");
  } else {
    if (harms.length) found.add("chord-shape");
    if (harms.some((h) => /5$/.test(h))) found.add("power-chord");
    if (harms.some((h) => !!chordShape(h)?.barre && chordShape(h)?.form.startsWith("barre"))) found.add("barre");
  }
  return CARDS.map((c) => c.id).filter((id) => found.has(id));
}
